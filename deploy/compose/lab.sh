#!/usr/bin/env bash
# Snare lab driver: up | down [-v] | status | bootstrap | logs [service]
#
# Requires: docker with compose v2, curl. Talks only to 127.0.0.1.
set -euo pipefail

cd "$(dirname "$0")"
COMPOSE=(docker compose -f compose.yaml)
SECRETS=secrets
ARTEX_API=http://127.0.0.1:8787
SNARE_API=http://127.0.0.1:8780

log() { printf '[lab] %s\n' "$*" >&2; }
die() { printf '[lab] error: %s\n' "$*" >&2; exit 1; }

randhex() { head -c "$1" /dev/urandom | od -An -tx1 | tr -d ' \n'; }

# ensure_env writes .env once: a random Postgres password and the path to the
# pinned ARTEX checkout. Existing values are never overwritten.
ensure_env() {
  if [[ ! -f .env ]]; then
    local src=../../../ARTEX
    if [[ ! -d $src && -d ../../../ARTEX-main ]]; then src=../../../ARTEX-main; fi
    umask 077
    {
      echo "# Generated by lab.sh. Local only; never commit."
      echo "POSTGRES_PASSWORD=$(randhex 24)"
      echo "ARTEX_SRC=$src"
      echo "# LLM hosts ARTEX may reach through the egress proxy (host:port, comma-separated):"
      echo "LLM_EGRESS_ALLOW=api.deepseek.com:443"
      echo "# LLM for ARTEX runs: DeepSeek through its OpenAI-compatible API."
      echo "ARTEX_LLM_PROVIDER=openai"
      echo "ARTEX_LLM_BASE_URL=https://api.deepseek.com"
      echo "ARTEX_LLM_MODEL=deepseek-flash"
      echo "# Paste your DeepSeek key after the = yourself. lab.sh never writes it."
      echo "OPENAI_API_KEY="
    } > .env
    log "wrote .env (ARTEX_SRC=$src)"
  fi
  local src
  src=$(grep -E '^ARTEX_SRC=' .env | cut -d= -f2- || true)
  src=${src:-../../../ARTEX}
  [[ -f $src/go.mod ]] || die "ARTEX checkout not found at $src (set ARTEX_SRC in deploy/compose/.env)"
  grep -q '^module github.com/Autumn-27/artex' "$src/go.mod" || die "$src does not look like ARTEX"
}

# ensure_secrets creates the lab secrets once. The directory is 0700 so other
# host users cannot read it; the files are 0644 so the non-root container
# users can read them through the bind mount (see docs/ASSUMPTIONS.md).
ensure_secrets() {
  mkdir -p "$SECRETS"
  chmod 700 "$SECRETS"
  local name
  for name in snare_api_token artex_admin_password artex_webhook_secret snare_scanner_secret; do
    if [[ ! -s $SECRETS/$name ]]; then
      randhex 24 > "$SECRETS/$name"
      log "generated secrets/$name"
    fi
    chmod 644 "$SECRETS/$name"
  done
}

wait_http() { # url, seconds
  local url=$1 deadline=$((SECONDS + $2))
  until curl -fsS -o /dev/null "$url"; do
    (( SECONDS < deadline )) || return 1
    sleep 2
  done
}

# bootstrap performs ARTEX's first-run claim: read the one-time setup token
# from the ARTEX log and POST /api/auth/init with the generated password.
bootstrap() {
  wait_http "$ARTEX_API/api/health" 300 || die "ARTEX did not become healthy"
  local status
  status=$(curl -fsS "$ARTEX_API/api/auth/status")
  if grep -q '"initialized":true' <<<"$status"; then
    log "ARTEX admin already initialized"
  else
    local token=""
    for _ in $(seq 1 30); do
      token=$("${COMPOSE[@]}" logs artex 2>/dev/null | grep -o 'Setup token for the /setup page: [0-9a-f]*' | tail -1 | awk '{print $NF}' || true)
      [[ -n $token ]] && break
      sleep 2
    done
    [[ -n $token ]] || die "setup token not found in ARTEX logs"
    local pw body code
    pw=$(cat "$SECRETS/artex_admin_password")
    body=$(printf '{"password":"%s","setup_token":"%s"}' "$pw" "$token")
    code=$(curl -sS -o /dev/null -w '%{http_code}' -H 'Content-Type: application/json' \
      --data-binary @- "$ARTEX_API/api/auth/init" <<<"$body")
    [[ $code == 200 ]] || die "ARTEX /api/auth/init returned HTTP $code"
    log "ARTEX admin initialized (password in deploy/compose/secrets/artex_admin_password)"
  fi
}

# artex_token logs in to ARTEX and prints the JWT.
artex_token() {
  local pw
  pw=$(cat "$SECRETS/artex_admin_password")
  printf '{"username":"ARTEX","password":"%s"}' "$pw" |
    curl -fsS -H 'Content-Type: application/json' --data-binary @- "$ARTEX_API/api/auth/login" |
    sed -n 's/.*"token":"\([^"]*\)".*/\1/p'
}

# harden_artex switches ARTEX's web search off and reads the setting back.
# It is off by default at the pin; setting it explicitly survives a UI change.
harden_artex() {
  local jwt out
  jwt=$(artex_token)
  [[ -n $jwt ]] || die "ARTEX login failed"
  curl -fsS -o /dev/null -X PUT -H "Authorization: Bearer $jwt" -H 'Content-Type: application/json' \
    --data '{"web_search_enabled":false}' "$ARTEX_API/api/settings"
  out=$(curl -fsS -H "Authorization: Bearer $jwt" "$ARTEX_API/api/settings")
  grep -q '"web_search_enabled":false' <<<"$out" || die "ARTEX web search is not off"
  log "ARTEX web search is off"
  # ARTEX's traffic capture is off by default, and while it is off ARTEX
  # gives its tools no proxy: no request carries the scanner header and no
  # finding gets bound proving exchanges. Turn it on.
  curl -fsS -o /dev/null -X PUT -H "Authorization: Bearer $jwt" -H 'Content-Type: application/json' \
    --data '{"traffic_capture":true}' "$ARTEX_API/api/settings"
  out=$(curl -fsS -H "Authorization: Bearer $jwt" "$ARTEX_API/api/settings")
  grep -q '"traffic_capture":true' <<<"$out" || die "ARTEX traffic capture is not on"
  log "ARTEX traffic capture is on (tools go through its proxy)"
  install_scanner_rule "$jwt"
}

# install_scanner_rule makes ARTEX's capture proxy add Snare's scanner
# identity header to every request it sends to host "snare". The value is a
# sensitive action: ARTEX keeps it out of its API, traces and rule snapshots,
# and its recorded exchanges hold the request as the tool sent it, before the
# rewrite. Idempotent: an existing rule with the same name is replaced. The
# secret goes to curl on stdin, never on a command line.
SCANNER_RULE=snare-scanner-identity
install_scanner_rule() {
  local jwt=$1 ids id secret out
  ids=$(curl -fsS -H "Authorization: Bearer $jwt" "$ARTEX_API/api/traffic/rewrite-rules" |
    grep -o "{\"id\":[0-9]*,\"name\":\"$SCANNER_RULE\"" | grep -o '[0-9][0-9]*' || true)
  for id in $ids; do
    curl -fsS -o /dev/null -X DELETE -H "Authorization: Bearer $jwt" "$ARTEX_API/api/traffic/rewrite-rules/$id"
  done
  secret=$(cat "$SECRETS/snare_scanner_secret")
  out=$(printf '{"name":"%s","phase":"request","priority":0,"matchers":{"host":"snare"},"actions":[{"type":"set_header","name":"X-Snare-Scanner","value":"%s","sensitive":true}],"note":"Installed by Snare lab.sh. Identifies ARTEX traffic to Snare so it never enters the benign corpus."}' "$SCANNER_RULE" "$secret" |
    curl -fsS -H "Authorization: Bearer $jwt" -H 'Content-Type: application/json' --data @- "$ARTEX_API/api/traffic/rewrite-rules")
  id=$(sed -n 's/^{"id":\([0-9]*\).*/\1/p' <<<"$out")
  [[ -n $id ]] || die "could not create the ARTEX scanner rewrite rule"
  out=$(curl -fsS -H "Authorization: Bearer $jwt" -H 'Content-Type: application/json' \
    --data '{"enabled":true}' "$ARTEX_API/api/traffic/rewrite-rules/$id/toggle")
  grep -q '"enabled":true' <<<"$out" || die "could not enable the ARTEX scanner rewrite rule"
  if grep -qF "$secret" <<<"$out"; then die "ARTEX echoed the scanner secret in its API"; fi
  log "ARTEX scanner identity rule installed (rule $id: header X-Snare-Scanner on requests to host snare)"
}

check_snare() {
  wait_http "$SNARE_API/healthz" 120 || die "Snare did not become healthy"
  local tok out
  tok=$(cat "$SECRETS/snare_api_token")
  out=$(curl -fsS -H "Authorization: Bearer $tok" "$SNARE_API/api/status")
  echo "$out"
  grep -q '"logged_in":true' <<<"$out" || die "Snare cannot log in to ARTEX"
}

# test_egress runs inside the ARTEX container and fails unless:
#   - direct connections to the internet fail (no route, no DNS);
#   - the egress proxy refuses an arbitrary host and a wrong port;
#   - ARTEX's own recording proxy cannot reach the internet;
#   - every allowlisted LLM host is reachable through the egress proxy
#     (any HTTP status counts: no API key is configured);
#   - nuclei loads its baked templates with no network.
# Two positive controls first show that lab targets are reachable, so the
# negative checks are not passing because something is simply down.
test_egress() {
  local allow fails=0
  # Same default as compose.yaml.
  allow=$(grep -E '^LLM_EGRESS_ALLOW=' .env | cut -d= -f2- || true)
  allow=${allow:-api.deepseek.com:443}
  ax() { "${COMPOSE[@]}" exec -T artex "$@"; }
  pass() { printf '  PASS  %s\n' "$*"; }
  fail() { printf '  FAIL  %s\n' "$*"; fails=$((fails + 1)); }

  echo "egress test (allowlist: $allow)"
  # Positive controls: lab targets are reachable, directly and through ARTEX's
  # recording proxy, so the failures below are the network's doing.
  if ax curl -fsS --max-time 8 -o /dev/null --noproxy '*' http://snare:8000/; then
    pass "control: the target through Snare's gateway (http://snare:8000) works"
  else fail "control: http://snare:8000 failed"; fi
  if ax curl -fsS --max-time 8 -o /dev/null -x http://127.0.0.1:8788 http://snare:8000/; then
    pass "control: the target through ARTEX recording proxy works"
  else fail "control: ARTEX recording proxy is not working"; fi
  if ax curl -sS --max-time 5 -o /dev/null --noproxy '*' http://juice-shop:3000/ 2>/dev/null; then
    fail "ARTEX reaches Juice Shop directly, bypassing Snare"
  else pass "ARTEX cannot reach Juice Shop directly (only through Snare)"; fi
  if ax curl -sS --max-time 8 -o /dev/null https://example.com 2>/dev/null; then
    fail "direct https://example.com succeeded"
  else pass "direct https://example.com fails"; fi
  if ax getent hosts example.com >/dev/null 2>&1; then
    fail "DNS for example.com resolves inside ARTEX"
  else pass "DNS for example.com does not resolve inside ARTEX"; fi
  local code
  code=$(ax curl -s --max-time 8 -o /dev/null -w '%{http_connect}' -x http://egress:3128 https://example.com 2>/dev/null || true)
  if [[ $code == 403 ]]; then pass "proxy refuses example.com (CONNECT 403)"
  else fail "proxy did not refuse example.com (CONNECT $code)"; fi
  local first=${allow%%,*}; first=${first%%:*}
  code=$(ax curl -s --max-time 8 -o /dev/null -w '%{http_connect}' -x http://egress:3128 "https://$first:8443" 2>/dev/null || true)
  if [[ $code == 403 ]]; then pass "proxy refuses $first on a non-allowlisted port"
  else fail "proxy did not refuse $first:8443 (CONNECT $code)"; fi
  if ax curl -sk --max-time 8 -o /dev/null -x http://127.0.0.1:8788 https://example.com 2>/dev/null; then
    fail "ARTEX recording proxy reached example.com"
  else pass "ARTEX recording proxy cannot reach example.com"; fi
  local h
  for h in ${allow//,/ }; do
    h=${h%%:*}
    code=$(ax curl -s --max-time 15 -o /dev/null -w '%{http_code}' -x http://egress:3128 "https://$h/" 2>/dev/null || true)
    if [[ $code =~ ^[1-5][0-9][0-9]$ ]]; then pass "allowed $h reachable through proxy (HTTP $code)"
    else fail "allowed $h not reachable through proxy (got '$code')"; fi
  done
  # Other LLM providers must be refused unless they are on the allowlist.
  for h in api.openai.com api.anthropic.com generativelanguage.googleapis.com openrouter.ai; do
    [[ ,$allow, == *",$h,"* || ,$allow, == *",$h:"* ]] && continue
    code=$(ax curl -s --max-time 8 -o /dev/null -w '%{http_connect}' -x http://egress:3128 "https://$h/" 2>/dev/null || true)
    if [[ $code == 403 ]]; then pass "proxy refuses $h, not on the allowlist (CONNECT 403)"
    else fail "proxy did not refuse $h (CONNECT $code)"; fi
  done
  local n
  n=$(ax sh -c 'nuclei -duc -tl -silent 2>/dev/null | wc -l' | tr -d ' \r')
  if (( n > 1000 )); then pass "nuclei lists $n baked templates offline"
  else fail "nuclei lists only $n templates offline"; fi
  (( fails == 0 )) || die "egress test: $fails check(s) failed"
  log "egress test passed"
}

# Services ARTEX can reach that may also sit on a non-internal network: each
# dials only fixed or allowlisted destinations, and the audit does not walk
# through them.
CONTAINMENT_EXCEPTIONS="egress artex-ui snare-ports"

# test_containment enforces the containment rule: ARTEX and every container
# ARTEX can reach, directly or through another container, must be on internal
# networks only.
# The exceptions are the egress proxy (allowlisted LLM hosts only), the
# artex-ui forwarder (dials only artex:8787) and snare-ports (dials only
# snare:8000 and snare:8780). New services, such as the M1
# Playwright runner, are covered automatically.
test_containment() {
  local fails=0 artex nets net c svc cnets n internal
  pass() { printf '  PASS  %s\n' "$*"; }
  fail() { printf '  FAIL  %s\n' "$*"; fails=$((fails + 1)); }
  echo "containment audit"
  # The Playwright runner exists only during a traffic run; start an idle one
  # (auto-removed when it exits) so the audit covers it too.
  "${COMPOSE[@]}" --profile traffic build -q playwright
  local pw
  pw=$("${COMPOSE[@]}" --profile traffic run -d --rm --no-deps --entrypoint sleep playwright 300)
  artex=$("${COMPOSE[@]}" ps -q artex)
  [[ -n $artex ]] || die "artex is not running"
  nets=$(docker inspect "$artex" --format '{{range $k, $v := .NetworkSettings.Networks}}{{$k}} {{end}}')
  for net in $nets; do
    internal=$(docker network inspect "$net" --format '{{.Internal}}')
    if [[ $internal == true ]]; then pass "artex network $net is internal"
    else fail "artex is on non-internal network $net"; fi
  done
  # Reachability is transitive: a container ARTEX can reach can reach the
  # containers on its own networks (Snare reaches Juice Shop on "target").
  # Walk networks breadth-first from ARTEX. Declared exceptions are not
  # walked through: they only forward to fixed or allowlisted destinations.
  local -a reachable=() queue=("$artex") seen_nets=()
  local cur cnet csvc
  while (( ${#queue[@]} > 0 )); do
    cur=${queue[0]}; queue=("${queue[@]:1}")
    for cnet in $(docker inspect "$cur" --format '{{range $k, $v := .NetworkSettings.Networks}}{{$k}} {{end}}'); do
      [[ " ${seen_nets[*]-} " == *" $cnet "* ]] && continue
      seen_nets+=("$cnet")
      for c in $(docker network inspect "$cnet" --format '{{range .Containers}}{{.Name}} {{end}}'); do
        [[ " ${reachable[*]-} " == *" $c "* ]] && continue
        reachable+=("$c")
        csvc=$(docker inspect "$c" --format '{{index .Config.Labels "com.docker.compose.service"}}')
        [[ " $CONTAINMENT_EXCEPTIONS " == *" $csvc "* ]] || queue+=("$c")
      done
    done
  done
  for c in ${reachable[@]+"${reachable[@]}"}; do
    svc=$(docker inspect "$c" --format '{{index .Config.Labels "com.docker.compose.service"}}')
    [[ $svc == artex ]] && continue
    if [[ " $CONTAINMENT_EXCEPTIONS " == *" $svc "* ]]; then
      pass "$svc is a declared exception (fixed or allowlisted destinations only)"
      continue
    fi
    cnets=$(docker inspect "$c" --format '{{range $k, $v := .NetworkSettings.Networks}}{{$k}} {{end}}')
    local ok=1
    for n in $cnets; do
      [[ $(docker network inspect "$n" --format '{{.Internal}}') == true ]] || { ok=0; fail "$svc (reachable from ARTEX) is on non-internal network $n"; }
    done
    (( ok )) && pass "$svc (reachable from ARTEX) is on internal networks only: $cnets"
  done

  # Behavioral probes: each reachable container fails to fetch an internet URL.
  if "${COMPOSE[@]}" exec -T juice-shop /nodejs/bin/node -e \
      "fetch('https://example.com').then(()=>process.exit(0),()=>process.exit(1))" >/dev/null 2>&1; then
    fail "juice-shop can fetch https://example.com"
  else pass "juice-shop cannot fetch https://example.com"; fi
  if "${COMPOSE[@]}" exec -T postgres wget -q -T 5 -O /dev/null https://example.com >/dev/null 2>&1; then
    fail "postgres can fetch https://example.com"
  else pass "postgres cannot fetch https://example.com"; fi
  if "${COMPOSE[@]}" exec -T snare /usr/local/bin/snare healthcheck -url https://example.com/ >/dev/null 2>&1; then
    fail "snare can fetch https://example.com"
  else pass "snare cannot fetch https://example.com"; fi
  if docker exec "$pw" node -e "fetch('https://example.com').then(()=>process.exit(0),()=>process.exit(1))" >/dev/null 2>&1; then
    fail "playwright can fetch https://example.com"
  else pass "playwright cannot fetch https://example.com"; fi
  docker stop -t 1 "$pw" >/dev/null 2>&1 || true
  (( fails == 0 )) || die "containment audit: $fails check(s) failed"
  log "containment audit passed"
}

# test_pivot tries the pivot an agent would use: Juice Shop's deliberate SSRF
# (POST /profile/image/url fetches imageUrl server-side), driven from inside
# the ARTEX container. Juice Shop stores an /assets/.../uploads/ path when the
# fetch succeeds and the raw URL when it fails, which is how the result is
# read back (after a fresh login, since whoami reads the login token).
test_pivot() {
  local fails=0 email pw tok img
  pass() { printf '  PASS  %s\n' "$*"; }
  fail() { printf '  FAIL  %s\n' "$*"; fails=$((fails + 1)); }
  ax() { "${COMPOSE[@]}" exec -T artex "$@"; }
  local js=http://snare:8000 # the only way ARTEX reaches Juice Shop
  echo "pivot test (Juice Shop SSRF, driven from ARTEX)"
  email="pivot-$(randhex 4)@lab.test"
  pw="Pivot-$(randhex 8)"
  ax curl -fsS -o /dev/null -H 'Content-Type: application/json' \
    --data "{\"email\":\"$email\",\"password\":\"$pw\",\"passwordRepeat\":\"$pw\"}" "$js/api/Users" ||
    die "pivot test: could not register a Juice Shop user"
  jlogin() {
    ax curl -fsS -H 'Content-Type: application/json' \
      --data "{\"email\":\"$email\",\"password\":\"$pw\"}" "$js/rest/user/login" |
      sed -n 's/.*"token":"\([^"]*\)".*/\1/p'
  }
  ssrf() { # url -> prints the stored profileImage
    tok=$(jlogin)
    [[ -n $tok ]] || die "pivot test: Juice Shop login failed"
    ax curl -s -o /dev/null -b "token=$tok" --data-urlencode "imageUrl=$1" "$js/profile/image/url"
    tok=$(jlogin)
    ax curl -fsS -b "token=$tok" "$js/rest/user/whoami" | sed -n 's/.*"profileImage":"\([^"]*\)".*/\1/p'
  }
  img=$(ssrf http://snare:8780/healthz)
  if [[ $img == /assets/public/images/uploads/* ]]; then
    pass "control: SSRF route fetches lab-internal http://snare:8780/healthz (stored $img)"
  else fail "control: SSRF route could not fetch a lab URL (stored '$img')"; fi
  img=$(ssrf https://example.com/)
  if [[ $img == https://example.com/ ]]; then
    pass "SSRF route cannot fetch https://example.com/ (Juice Shop fell back to storing the URL)"
  else fail "SSRF route fetched https://example.com/ (stored '$img')"; fi
  local why
  why=$("${COMPOSE[@]}" logs --since 2m juice-shop 2>/dev/null | grep -o 'Error retrieving user profile image: [^;]*' | tail -1 || true)
  [[ -n $why ]] && printf '        juice-shop log: %s\n' "$why"
  (( fails == 0 )) || die "pivot test: $fails check(s) failed"
  log "pivot test passed"
}

# traffic runs the Playwright happy-path suite through Snare's gateway.
traffic() {
  mkdir -p run/playwright
  "${COMPOSE[@]}" --profile traffic build playwright
  "${COMPOSE[@]}" --profile traffic run --rm playwright "$@"
}

# jval prints a top-level string value from a flat JSON file.
jval() { sed -n "s/^ *\"$1\": \"\(.*\)\",\{0,1\}$/\1/p" "$2" | head -1; }

# corpus_check dumps every stored exchange of the juice-shop route (already
# redacted, decrypted by Snare) and fails if any value the Playwright suite
# typed in appears in it.
corpus_check() {
  local fails=0 dump n key v typed files=()
  for typed in run/playwright/typed-values-*.json; do [[ -f $typed ]] && files+=("$typed"); done
  (( ${#files[@]} > 0 )) || die "no typed values under run/playwright; run ./lab.sh traffic first"
  dump=$("${COMPOSE[@]}" exec -T snare /usr/local/bin/snare corpus dump -config /etc/snare/snare.yaml -route juice-shop)
  n=$(grep -c '"id":' <<<"$dump" || true)
  echo "corpus check: $n stored exchanges on route juice-shop, ${#files[@]} Playwright run(s)"
  (( n > 0 )) || die "the corpus is empty"
  for typed in "${files[@]}"; do
    for key in email password answer card name street mobile cardName; do
      v=$(jval "$key" "$typed")
      [[ -n $v ]] || { printf '  FAIL  %s: typed value %s missing\n' "$typed" "$key"; fails=$((fails + 1)); continue; }
      if grep -qF -- "$v" <<<"$dump"; then
        printf '  FAIL  %s: typed %s found in the stored corpus\n' "${typed##*/}" "$key"; fails=$((fails + 1))
      fi
    done
  done
  (( fails == 0 )) && printf '  PASS  none of the %d typed values per run (email, password, security answer, card, name, street, mobile, card holder) is in the stored corpus\n' 8
  local kinds
  kinds=$(grep -o '\[REDACTED:[a-z]*\]' <<<"$dump" | sort | uniq -c | awk '{printf "%s %s, ", $2, $1}')
  echo "  redaction placeholders: ${kinds%, }"
  (( fails == 0 )) || die "corpus check: $fails value(s) stored unredacted"
  log "corpus check passed"
}

# test_corpus_exclusion checks that scanner traffic never enters the benign
# corpus, by each way Snare identifies it:
#   - header: requests through ARTEX's capture proxy carry X-Snare-Scanner;
#   - source: direct requests from ARTEX come from its fixed lab address;
#   - user agent: a sqlmap User-Agent from another container.
# It also checks that a wrong header value is treated as forged (counted, not
# recorded), that the header never reaches the corpus, and that ARTEX's own
# traffic record holds no copy of the secret. A browser-like request is the
# control: it must be recorded.
test_corpus_exclusion() {
  local tok before mid after st0 st1 i fails=0 marker secret id ex
  pass() { printf '  PASS  %s\n' "$*"; }
  fail() { printf '  FAIL  %s\n' "$*"; fails=$((fails + 1)); }
  tok=$(cat "$SECRETS/snare_api_token")
  secret=$(cat "$SECRETS/snare_scanner_secret")
  stored() { curl -fsS -H "Authorization: Bearer $tok" "$SNARE_API/api/corpus/coverage" | sed -n 's/^{"routes":\[{"route":"juice-shop","requests":\([0-9]*\).*/\1/p'; }
  counter() { sed -n "s/.*\"$1\":\([0-9]*\).*/\1/p" <<<"$2"; }
  status() { curl -fsS -H "Authorization: Bearer $tok" "$SNARE_API/api/status"; }
  settle() { sleep 1.5; } # the recorder writes in batches off the request path
  jsfetch() { # url user-agent [header-value]
    "${COMPOSE[@]}" exec -T juice-shop /nodejs/bin/node -e \
      "const h={'User-Agent':process.argv[2]};if(process.argv[3])h['X-Snare-Scanner']=process.argv[3];fetch(process.argv[1],{headers:h}).then(r=>process.exit(r.ok?0:1),()=>process.exit(1))" \
      "$1" "$2" "${3:-}"
  }
  marker=excl$(randhex 3)
  echo "corpus exclusion test (scanner traffic must not enter the benign corpus)"
  before=$(stored); before=${before:-0}; st0=$(status)
  for i in 1 2 3; do
    "${COMPOSE[@]}" exec -T artex curl -fsS -o /dev/null -x http://127.0.0.1:8788 \
      "http://snare:8000/rest/products/search?q=$marker-proxy$i" || die "corpus exclusion: ARTEX's capture proxy could not reach Snare"
    "${COMPOSE[@]}" exec -T artex curl -fsS -o /dev/null --noproxy '*' \
      "http://snare:8000/rest/products/search?q=$marker-direct$i" || die "corpus exclusion: ARTEX could not reach Snare directly"
  done
  jsfetch "http://snare:8000/rest/products/search?q=$marker-ua" 'sqlmap/1.8.2#stable (https://sqlmap.org)' ||
    die "corpus exclusion: Juice Shop could not reach Snare's gateway"
  settle; mid=$(stored); mid=${mid:-0}; st1=$(status)
  local dh ds da
  dh=$(( $(counter excluded_scanner_header "$st1") - $(counter excluded_scanner_header "$st0") ))
  ds=$(( $(counter excluded_scanner_source "$st1") - $(counter excluded_scanner_source "$st0") ))
  da=$(( $(counter excluded_scanner_agent "$st1") - $(counter excluded_scanner_agent "$st0") ))
  if [[ $mid == "$before" ]]; then pass "9 scanner requests were proxied and none was recorded ($before stored before and after)"
  else fail "corpus grew from $before to $mid on scanner traffic"; fi
  if (( dh == 3 )); then pass "3 requests through ARTEX's capture proxy identified by the scanner header"
  else fail "expected 3 header identifications, got $dh (is the ARTEX rewrite rule installed? ./lab.sh bootstrap)"; fi
  if (( ds == 3 )); then pass "3 direct requests from ARTEX (no proxy, no header) identified by its fixed address"
  else fail "expected 3 source identifications, got $ds"; fi
  if (( da == 1 )); then pass "1 request with a sqlmap User-Agent identified by User-Agent"
  else fail "expected 1 User-Agent identification, got $da"; fi

  jsfetch "http://snare:8000/rest/products/search?q=$marker-wrong" 'Mozilla/5.0 (X11; Linux x86_64) Chrome/159.0' 'not-the-secret' ||
    die "corpus exclusion: wrong-header request failed"
  jsfetch "http://snare:8000/rest/products/search?q=$marker-control" 'Mozilla/5.0 (X11; Linux x86_64) Chrome/159.0' ||
    die "corpus exclusion: control request failed"
  settle; after=$(stored); after=${after:-0}; st1=$(status)
  if (( after == mid + 1 )); then pass "control: a browser-like request is recorded, the one with a forged header is not ($mid -> $after)"
  else fail "expected $((mid + 1)) stored (control only), got $after"; fi
  if (( $(counter scanner_header_mismatch "$st1") > $(counter scanner_header_mismatch "$st0") )); then pass "the wrong header value was counted as forged"
  else fail "wrong header value not counted"; fi
  if "${COMPOSE[@]}" exec -T snare /usr/local/bin/snare corpus dump -config /etc/snare/snare.yaml -route juice-shop | grep -qi 'x-snare-scanner'; then
    fail "a stored request carries the scanner header"
  else pass "no stored request carries the scanner header"; fi

  # ARTEX's own record of the proxied requests must not contain the secret.
  local jwt
  jwt=$(artex_token)
  # Tools get ARTEX's proxy (and so the header) only while its traffic
  # capture is on; the curl above names the proxy explicitly, so check it.
  if curl -fsS -H "Authorization: Bearer $jwt" "$ARTEX_API/api/settings" | grep -q '"traffic_capture":true'; then
    pass "ARTEX traffic capture is on, so its tools are given the proxy"
  else fail "ARTEX traffic capture is off: its tools bypass the proxy and send no scanner header"; fi
  local ids n=0 leaked=0
  ids=$(curl -fsS -H "Authorization: Bearer $jwt" "$ARTEX_API/api/traffic?host=snare&size=200" |
    grep -o '"id":"[^"]*"' | cut -d'"' -f4 || true)
  for id in $ids; do
    ex=$(curl -fsS -H "Authorization: Bearer $jwt" "$ARTEX_API/api/traffic/exchange?id=$id")
    n=$((n + 1))
    if grep -qF "$secret" <<<"$ex" || grep -qi 'x-snare-scanner' <<<"$ex"; then leaked=$((leaked + 1)); fi
  done
  if (( n == 0 )); then fail "ARTEX recorded no exchange to host snare"
  elif (( leaked > 0 )); then fail "$leaked of ARTEX's $n recorded exchanges to snare contain the scanner header or secret"
  else pass "none of ARTEX's $n recorded exchanges to snare contains the scanner header or secret"; fi
  st1=$(status)
  printf '        gateway counters: %s\n' "$(grep -o '"\(excluded_[a-z_]*\|scanner_header_mismatch\)":[0-9]*' <<<"$st1" | tr '\n' ' ')"
  (( fails == 0 )) || die "corpus exclusion: $fails check(s) failed"
  log "corpus exclusion test passed"
}

# ---------------------------------------------------------------- LLM runs ---
# Prices per million tokens (deepseek-flash, off-peak): input on a cache miss,
# input on a cache hit, output. Peak (01:00-04:00 and 06:00-10:00 UTC on
# weekdays) doubles every rate. ARTEX's input_tokens include its
# cache_read_tokens, so two figures are kept: the upper bound prices every
# input token as a miss, the estimated actual prices cache reads as hits.
PRICE_IN=0.15
PRICE_CACHE=0.003
PRICE_OUT=0.60
# Shares seen in the first capture run, for estimating a run before it
# starts: cache reads as a share of input, output as a share of all tokens.
EST_CACHE_SHARE=0.915
EST_OUT_SHARE=0.034
SPEND_FILE=../../bench/results/llm-spend.md

# is_peak [epoch] prints 1 during DeepSeek peak hours, else 0.
is_peak() {
  local t=${1:-$(date -u +%s)} dow hour
  dow=$(date -u -r "$t" +%u 2>/dev/null || date -u -d "@$t" +%u)
  hour=$(date -u -r "$t" +%H 2>/dev/null || date -u -d "@$t" +%H); hour=$((10#$hour))
  if (( dow <= 5 )) && { (( hour >= 1 && hour < 4 )) || (( hour >= 6 && hour < 10 )); }; then echo 1; else echo 0; fi
}

# llm_key_present succeeds when .env has a non-empty OPENAI_API_KEY. It never
# prints the value.
llm_key_present() { grep -qE '^OPENAI_API_KEY=.+' .env; }

# outcome_line TASK prints "input output tool_calls wall_seconds status"
# from ARTEX's outcome endpoint.
outcome_json() { curl -fsS -H "Authorization: Bearer $(artex_token)" "$ARTEX_API/api/tasks/$1/outcome"; }
jnum() { sed -n "s/.*\"$1\":\([0-9]*\).*/\1/p" <<<"$2" | head -1; }
cost_upper() { # input output peak(0|1) -> dollars, every input token a cache miss
  awk -v i="$1" -v o="$2" -v p="$3" -v pi="$PRICE_IN" -v po="$PRICE_OUT" \
    'BEGIN { m = (p == 1) ? 2 : 1; printf "%.4f", (i * pi + o * po) * m / 1e6 }'
}
cost_actual() { # input cache_read output peak(0|1) -> dollars, cache reads at the hit rate
  awk -v i="$1" -v c="$2" -v o="$3" -v p="$4" -v pi="$PRICE_IN" -v pc="$PRICE_CACHE" -v po="$PRICE_OUT" \
    'BEGIN { m = (p == 1) ? 2 : 1; printf "%.4f", ((i - c) * pi + c * pc + o * po) * m / 1e6 }'
}
# estimate TOTAL_TOKENS PEAK prints "upper actual" for a run of that size,
# using the shares from the first capture run.
estimate() {
  local out inp cache
  out=$(awk -v t="$1" -v s="$EST_OUT_SHARE" 'BEGIN { printf "%d", t * s }')
  inp=$(( $1 - out ))
  cache=$(awk -v i="$inp" -v s="$EST_CACHE_SHARE" 'BEGIN { printf "%d", i * s }')
  echo "$(cost_upper "$inp" "$out" "$2") $(cost_actual "$inp" "$cache" "$out" "$2")"
}
# artex_budget prints ARTEX's task token budget from its container env.
artex_budget() {
  docker inspect "$("${COMPOSE[@]}" ps -q artex)" --format '{{range .Config.Env}}{{println .}}{{end}}' |
    sed -n 's/^ARTEX_TASK_BUDGET_TOKENS=//p'
}

# capture-run: the one recorded ARTEX run against Juice Shop through Snare.
# Without --yes it only prints the plan. It:
#   1. checks the key is set (without printing it), the egress allowlist is
#      DeepSeek only, the model id exists (GET /models, no tokens), and that
#      it is off-peak (--allow-peak overrides);
#   2. restarts Snare with the scanner capture on;
#   3. sets ARTEX's task budget to --tokens (ARTEX reads it from its
#      environment, so the container is recreated when it differs), checks
#      ARTEX's traffic capture is on, creates the task (wall-clock limit), scoped to
#      http://snare:8000, and polls the outcome every 60 s, pausing the task
#      if tokens pass the hard stop;
#   4. turns the capture off and copies the capture and outcome out to
#      run/capture/<id>/, and appends the run to bench/results/llm-spend.md.
CAPTURE_TOKENS=${CAPTURE_TOKENS:-2000000}
CAPTURE_HARD_STOP=${CAPTURE_HARD_STOP:-2400000}
CAPTURE_TIMEOUT=${CAPTURE_TIMEOUT:-5400}
capture_run() {
  local yes=0 allow_peak=0
  while (( $# )); do
    case $1 in
      --yes) yes=1 ;;
      --allow-peak) allow_peak=1 ;;
      --tokens) CAPTURE_TOKENS=$2; shift ;;
      --hard-stop) CAPTURE_HARD_STOP=$2; shift ;;
      *) die "capture-run: unknown option $1" ;;
    esac
    shift
  done
  (( CAPTURE_HARD_STOP > CAPTURE_TOKENS )) || die "capture-run: --hard-stop must be above --tokens"
  local model allow peak cur capture_on
  model=$(grep -E '^ARTEX_LLM_MODEL=' .env | cut -d= -f2- || true)
  allow=$(grep -E '^LLM_EGRESS_ALLOW=' .env | cut -d= -f2- || true)
  peak=$(is_peak)
  cur=$(artex_budget)
  if curl -fsS -H "Authorization: Bearer $(artex_token)" "$ARTEX_API/api/settings" | grep -q '"traffic_capture":true'; then
    capture_on="on (tools go through its proxy: scanner header, bound evidence)"
  else capture_on="OFF: run ./lab.sh bootstrap first"; fi
  local b_off h_off h_peak
  b_off=$(estimate "$CAPTURE_TOKENS" 0); h_off=$(estimate "$CAPTURE_HARD_STOP" 0); h_peak=$(estimate "$CAPTURE_HARD_STOP" 1)
  cat <<EOF
capture run plan
  target       http://snare:8000 (Juice Shop behind Snare; ARTEX cannot reach Juice Shop directly)
  model        ${model:-<unset>} via ${allow:-<unset>} (OpenAI-compatible API)
  budget       $CAPTURE_TOKENS tokens (ARTEX task budget, input + output; ARTEX now has ${cur:-unset}$( [[ $cur == "$CAPTURE_TOKENS" ]] || echo ", will be set" )), hard stop at $CAPTURE_HARD_STOP, wall clock ${CAPTURE_TIMEOUT}s
  ARTEX capture $capture_on
  cost (USD)   upper bound (all input as cache misses) / estimated actual (cache share from run 1):
                 budget used, off-peak      ${b_off% *} / ${b_off#* }
                 at the hard stop, off-peak ${h_off% *} / ${h_off#* }
                 at the hard stop, peak     ${h_peak% *} / ${h_peak#* }
  now          $(date -u +%Y-%m-%dT%H:%MZ) is $( ((peak)) && echo "PEAK (double price)" || echo off-peak)
  capture      Snare writes ARTEX's traffic to run/capture/<task>/scanner.jsonl
EOF
  (( yes )) || { echo "not started: pass --yes to run it"; return 0; }
  llm_key_present || die "OPENAI_API_KEY is empty in deploy/compose/.env"
  [[ $allow == api.deepseek.com:443 ]] || die "LLM_EGRESS_ALLOW must be exactly api.deepseek.com:443 (is '$allow')"
  if (( peak && !allow_peak )); then die "it is DeepSeek peak time (double price); wait, or pass --allow-peak"; fi
  [[ $capture_on == on* ]] ||
    die "ARTEX traffic capture is off: tools would bypass its proxy (no scanner header, no bound evidence); run ./lab.sh bootstrap"
  if [[ $(artex_budget) != "$CAPTURE_TOKENS" ]]; then
    # Shell environment beats .env in compose interpolation; the next plain
    # ./lab.sh up returns ARTEX to the .env or default budget.
    ARTEX_TASK_BUDGET_TOKENS=$CAPTURE_TOKENS "${COMPOSE[@]}" up -d --wait artex >/dev/null
    [[ $(artex_budget) == "$CAPTURE_TOKENS" ]] || die "could not set ARTEX's task budget to $CAPTURE_TOKENS"
    log "ARTEX task budget set to $CAPTURE_TOKENS (container recreated)"
    curl -fsS -H "Authorization: Bearer $(artex_token)" "$ARTEX_API/api/settings" | grep -q '"traffic_capture":true' ||
      die "ARTEX traffic capture is off after the restart"
  fi

  # The key is read inside the ARTEX container from its own environment and
  # handed to curl on stdin, so it is never on a command line or in output.
  local models
  models=$("${COMPOSE[@]}" exec -T artex sh -c \
    'printf "Authorization: Bearer %s\n" "$OPENAI_API_KEY" | curl -fsS --max-time 20 -x http://egress:3128 -H @- https://api.deepseek.com/models' 2>/dev/null) ||
    die "GET https://api.deepseek.com/models failed (key not loaded into ARTEX? run ./lab.sh up after editing .env)"
  grep -q "\"id\":\"$model\"" <<<"$models" ||
    die "model '$model' is not offered by DeepSeek; available: $(grep -o '"id":"[^"]*"' <<<"$models" | cut -d'"' -f4 | tr '\n' ' ')"
  echo "  model check  '$model' is offered (GET /models, no tokens used)"

  local stamp file
  stamp=$(date -u +%Y%m%dT%H%M%SZ)
  file=/var/lib/snare/scanner-capture-$stamp.jsonl
  SNARE_SCANNER_CAPTURE_FILE=$file "${COMPOSE[@]}" up -d --wait snare >/dev/null
  log "scanner capture on: $file"

  local jwt body out task start
  jwt=$(artex_token)
  body=$(cat <<'JSON'
{"name":"snare-capture-juice-shop",
 "description":"Authorized penetration test of an OWASP Juice Shop lab instance. The only target is http://snare:8000 (a gateway in front of the application). Everything runs in an isolated lab.",
 "goal":"Find and confirm as many distinct vulnerabilities as possible in the web application at http://snare:8000, each with the HTTP request and response that prove it. Do not test any other host or port; in particular, leave http://snare:8780 alone.",
 "timeout_seconds":TIMEOUT,
 "target_gate":false,
 "intercept_rules":[
   {"enabled":true,"action":"block","kind":"fuzzy_url","pattern":"snare:8780","note":"Snare's own API is not a target"},
   {"enabled":true,"action":"block","kind":"exact_domain","pattern":"postgres","note":"ARTEX's database is not a target"},
   {"enabled":true,"action":"block","kind":"exact_domain","pattern":"egress","note":"the egress proxy is not a target"}
 ]}
JSON
)
  body=${body/TIMEOUT/$CAPTURE_TIMEOUT}
  start=$(date -u +%s)
  out=$(curl -fsS -H "Authorization: Bearer $jwt" -H 'Content-Type: application/json' --data "$body" "$ARTEX_API/api/tasks") ||
    die "ARTEX refused the task"
  # ARTEX returns the id as a JSON string ("id":"1").
  task=$(grep -o '"id":"\{0,1\}[0-9][0-9]*' <<<"$out" | head -1 | grep -o '[0-9][0-9]*$' || true)
  if [[ -z $task ]]; then
    log "could not read the task id; the task may be running: check ./lab.sh and ARTEX's UI, then run ./lab.sh capture-watch TASK $file $start"
    die "could not read the task id"
  fi
  log "task $task started at $(date -u +%H:%MZ)"
  mkdir -p "run/capture/$task"
  printf '%s\n' "$out" > "run/capture/$task/task-created.json"
  capture_watch "$task" "$file" "$start"
}

# capture_watch TASK CAPTURE_FILE START_EPOCH polls a running capture task,
# pauses it past the hard stop, and when it ends turns the capture off, copies
# the capture and outcome out, and records the spend. capture_run calls it;
# it can also be attached to a task that is already running.
capture_watch() {
  local task=$1 file=$2 start=$3 dir=run/capture/$1
  mkdir -p "$dir"

  local o in_t out_t cache calls wall status tok
  while :; do
    sleep 60
    o=$(outcome_json "$task") || continue
    in_t=$(jnum input_tokens "$o"); out_t=$(jnum output_tokens "$o"); cache=$(jnum cache_read_tokens "$o")
    calls=$(jnum tool_calls "$o"); wall=$(jnum wall_seconds "$o")
    status=$(sed -n 's/.*"status":"\([a-z_]*\)".*/\1/p' <<<"$o" | head -1)
    tok=$(( ${in_t:-0} + ${out_t:-0} ))
    printf '  %s  %-8s tokens %8d (in %d, cache %d, out %d)  tool calls %4d  wall %5ds  $%s upper / $%s est.\n' \
      "$(date -u +%H:%M)" "$status" "$tok" "${in_t:-0}" "${cache:-0}" "${out_t:-0}" "${calls:-0}" "${wall:-0}" \
      "$(cost_upper "${in_t:-0}" "${out_t:-0}" "$(is_peak)")" "$(cost_actual "${in_t:-0}" "${cache:-0}" "${out_t:-0}" "$(is_peak)")"
    if (( tok > CAPTURE_HARD_STOP )); then
      curl -fsS -o /dev/null -H "Authorization: Bearer $(artex_token)" -H 'Content-Type: application/json' \
        --data '{"action":"pause"}' "$ARTEX_API/api/tasks/$task/control" || true
      log "hard stop: $tok tokens > $CAPTURE_HARD_STOP, task paused"
      break
    fi
    # Keep polling only while ARTEX is working; anything else (completed,
    # timeout, stopped, paused, quota_exhausted, chain_exhausted, ...) ends it.
    case $status in running|queued|created|pending|"") ;; *) log "task $task is $status"; break ;; esac
  done
  sleep 5
  outcome_json "$task" > "$dir/outcome.json"
  "${COMPOSE[@]}" up -d --wait snare >/dev/null # capture off
  "${COMPOSE[@]}" cp "snare:$file" "$dir/scanner.jsonl" >/dev/null
  chmod 600 "$dir/scanner.jsonl"
  log "capture off; $(wc -l < "$dir/scanner.jsonl" | tr -d ' ') exchanges in $dir/scanner.jsonl"
  record_spend "$task" "capture run (Juice Shop through Snare, $(artex_budget)-token budget)" "$start" "$(date -u +%s)"
}

# record_spend TASK DESCRIPTION START END appends one row to the spend log
# from ARTEX's outcome. A run that touches peak hours is priced at peak.
record_spend() {
  local task=$1 what=$2 start=$3 end=$4 o in_t out_t cache calls wall peak=0 t upper actual
  o=$(outcome_json "$task")
  in_t=$(jnum input_tokens "$o"); out_t=$(jnum output_tokens "$o"); cache=$(jnum cache_read_tokens "$o")
  calls=$(jnum tool_calls "$o"); wall=$(jnum wall_seconds "$o")
  for (( t = start; t <= end; t += 600 )); do (( $(is_peak "$t") )) && peak=1; done
  (( $(is_peak "$end") )) && peak=1
  upper=$(cost_upper "${in_t:-0}" "${out_t:-0}" "$peak")
  actual=$(cost_actual "${in_t:-0}" "${cache:-0}" "${out_t:-0}" "$peak")
  printf '| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |\n' "$(date -u -r "$start" +%Y-%m-%dT%H:%MZ 2>/dev/null || date -u -d "@$start" +%Y-%m-%dT%H:%MZ)" \
    "$task" "$what" "${in_t:-0}" "${cache:-0}" "${out_t:-0}" "${calls:-0}" "${wall:-0}" "$( ((peak)) && echo peak || echo off-peak)" "\$$upper" "\$$actual" >> "$SPEND_FILE"
  spend_total
  log "spend recorded in bench/results/llm-spend.md: \$$actual estimated actual (\$$upper upper bound) this run"
}

# spend_total rewrites the "Total so far" line from the table rows.
spend_total() {
  local sums
  sums=$(awk -F'|' '/^\| 20[0-9][0-9]-/ { u = $11; a = $12; gsub(/[ $]/, "", u); gsub(/[ $]/, "", a); tu += u; ta += a; n++ }
    END { printf "%.4f %.4f %d", ta, tu, n }' "$SPEND_FILE")
  set -- $sums
  sed -i.bak "s/^Total so far: .*/Total so far: \$$1 estimated actual, \$$2 upper bound, of \$5.00 ($3 runs)/" "$SPEND_FILE" && rm -f "$SPEND_FILE.bak"
  log "total so far: \$$1 estimated actual, \$$2 upper bound"
}

